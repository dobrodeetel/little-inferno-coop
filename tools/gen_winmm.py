"""Generate src/winmm_forwards.h: a jump stub for every export of the system winmm.dll.

Usage: python -I gen_winmm.py <SysWOW64\\winmm.dll> <out.h>
Each export N gets a naked x86 stub `jmp [g_winmm[i]]`; winmm_resolve() fills the table
from the real DLL. Needs pefile.
"""
import sys

import pefile


def main():
    dll, out = sys.argv[1:3]
    pe = pefile.PE(dll, fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
    syms = [(s.ordinal, s.name.decode() if s.name else None) for s in pe.DIRECTORY_ENTRY_EXPORT.symbols]
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/gen_winmm.py, do not edit.\n#pragma once\n")
        f.write(f"static void* g_winmm[{len(syms)}];\n")
        f.write("static const struct { const char* name; WORD ordinal; } g_winmm_names[] = {\n")
        for o, n in syms:
            f.write(f'    {{{"0" if n is None else chr(34) + n + chr(34)}, {o}}},\n')
        f.write("};\n")
        for i, (o, n) in enumerate(syms):
            f.write(f"extern \"C\" __declspec(naked) void W_{i}() {{ __asm jmp dword ptr [g_winmm + {i * 4}] }}\n")
            if n is None:
                f.write(f'#pragma comment(linker, "/EXPORT:__ord{o}=_W_{i},@{o},NONAME")\n')
            else:
                f.write(f'#pragma comment(linker, "/EXPORT:{n}=_W_{i},@{o}")\n')
        f.write(
            "static bool winmm_resolve(HMODULE real) {\n"
            "    for (size_t i = 0; i < sizeof(g_winmm) / sizeof(g_winmm[0]); i++) {\n"
            "        g_winmm[i] = g_winmm_names[i].name ? (void*)GetProcAddress(real, g_winmm_names[i].name)\n"
            "                                           : (void*)GetProcAddress(real, MAKEINTRESOURCEA(g_winmm_names[i].ordinal));\n"
            "    }\n"
            "    return true;\n"
            "}\n"
        )
    print(f"{len(syms)} exports")


if __name__ == "__main__":
    main()
